/**
 * Builds the default filesystem out of the `defaultfs/` folder at the root of
 * the repository — the folder sitting next to index.html and the README.
 *
 *   npm run gen:defaultfs     (also run by `npm run build`)
 *
 * Everything a brand-new account or a guest finds when they first boot comes
 * from those files. They are ordinary files on disk, so they can be read,
 * edited and diffed like the rest of the repository, instead of being string
 * literals buried in a TypeScript module.
 *
 * The output is src/os/defaultfs.ts: a plain object describing the tree, which
 * the virtual filesystem turns into nodes. Because it is generated into the
 * bundle, the running desktop never has to fetch these files — the site stays
 * completely self-contained and works with no network at all.
 *
 * Empty directories are real empty directories on disk, so they survive being
 * checked out and are still here to be listed.
 *
 * The README.md in that folder explains it to a person reading the repository.
 * It is not part of the filesystem it describes, so it is left out: a new
 * account should not boot to find one sitting at /.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { resolve, dirname, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = resolve(root, 'defaultfs')

/* The mime type is carried in the tree because the desktop decides which app
   opens a file from it, and guessing from the extension gets .conf and
   extensionless files wrong. Only the ones that are not plain text are
   recorded; everything else is text/plain. */
const MIME = {
  '.ogg': 'audio/ogg',
  '.wav': 'audio/wav',
  '.mp3': 'audio/mpeg',
  '.webm': 'video/webm',
  '.mp4': 'video/mp4',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.svg': 'image/svg+xml',
  '.gif': 'image/gif',
  '.html': 'text/html',
  '.htm': 'text/html',
  '.css': 'text/css',
  '.js': 'text/javascript',
  '.mjs': 'text/javascript',
  '.json': 'application/json',
  '.ini': 'text/plain',
  '.md': 'text/markdown',
}

const ext = (name) => {
  const i = name.lastIndexOf('.')
  return i < 0 ? '' : name.slice(i).toLowerCase()
}

/* This folder is also a place a person reads, so it is allowed to explain
   itself. The README describing it is not part of the filesystem it describes,
   and a new account should not boot to find one at /. */
const IGNORED = new Set(['README.md', 'readme.md', 'README'])

/* Walk the folder into nested {name -> node} maps. Directories are listed
   alphabetically so the generated module does not reshuffle itself on every
   build for no reason and pollute the diff. */
function walk(abs, isRoot = false) {
  const out = {}
  for (const name of readdirSync(abs).sort()) {
    if (isRoot && IGNORED.has(name)) continue
    const full = resolve(abs, name)
    const st = statSync(full)
    if (st.isDirectory()) out[name] = { type: 'dir', children: walk(full) }
    else {
      const node = { type: 'file', content: readFileSync(full, 'utf8') }
      const mime = MIME[ext(name)]
      if (mime && mime !== 'text/plain') node.mime = mime
      out[name] = node
    }
  }
  return out
}

const tree = walk(SRC, true)

/* Counted so the generated header can say what it contains, and so a check can
   assert the folder and the module agree. */
let files = 0
let dirs = 0
const count = (node) => {
  if (node.type === 'dir') {
    dirs += 1
    for (const c of Object.values(node.children)) count(c)
  } else files += 1
}
for (const c of Object.values(tree)) count(c)

const body = JSON.stringify(tree, null, 2)

const out = `/* Generated by scripts/gen-defaultfs.mjs from the defaultfs/ folder at the
 * root of the repository. Do not edit by hand — edit the files there and run
 * \`npm run gen:defaultfs\` (or \`npm run build\`, which runs it for you).
 *
 * This is the filesystem every new account and every guest starts with:
 * ${files} files in ${dirs} directories, read straight off disk so it can be
 * read and changed like any other part of the repository. It is compiled into
 * the bundle, so the desktop needs no network to produce it.
 */
export interface DefaultNode {
  type: 'dir' | 'file'
  children?: Record<string, DefaultNode>
  content?: string
  mime?: string
}

export const DEFAULT_FILESYSTEM: Record<string, DefaultNode> = ${body}

export const DEFAULT_FILE_COUNT = ${files}
export const DEFAULT_DIR_COUNT = ${dirs}
`

const target = resolve(root, 'src/os/defaultfs.ts')
const before = (() => {
  try { return readFileSync(target, 'utf8') } catch { return null }
})()
writeFileSync(target, out)
const changed = before !== out
console.log(`• defaultfs: ${files} files in ${dirs} directories → src/os/defaultfs.ts${changed ? '' : ' (unchanged)'}`)
export { relative }
