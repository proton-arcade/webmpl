/* Builds the application index from the source, rather than from a list
 * somebody has to remember to keep up to date.
 *
 * For every app in the registry it records the name, the summary, the
 * description, the file that implements it, and the modules that file imports —
 * all read out of src/apps, so the index cannot drift from the code.
 *
 * Written to src/os/appindex.ts, which the desktop reads to lay out
 * /usr/share/applications.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { resolve, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const appsDir = resolve(root, 'src/apps')

/* which component name belongs to which app id, straight from the registry */
const registry = readFileSync(resolve(appsDir, 'registry.tsx'), 'utf8')
const byComponent = new Map()
const entryRe = /import\s+(\w+)\s+from\s+'\.\/([^']+)'/g
let m
while ((m = entryRe.exec(registry))) byComponent.set(m[1], `src/apps/${m[2]}.tsx`)

/* and which component each app entry uses */
const apps = []
const appRe = /\{\s*id:\s*'([^']+)',([\s\S]*?)\n  \},/g
while ((m = appRe.exec(registry))) {
  const id = m[1]
  const body = m[2]
  const pick = (key) => {
    const r = new RegExp(`${key}:\\s*'((?:[^'\\\\]|\\\\.)*)'`).exec(body)
    return r ? r[1].replace(/\\'/g, "'") : ''
  }
  const comp = /component:\s*(\w+)/.exec(body)
  const cats = /categories:\s*\[([^\]]*)\]/.exec(body)
  apps.push({
    id,
    name: pick('name'),
    summary: pick('generic'),
    description: pick('comment'),
    file: comp ? byComponent.get(comp[1]) ?? '' : '',
    categories: cats
      ? cats[1]
        .split(',')
        .map((s) => s.trim().replace(/^'|'$/g, ''))
        .filter(Boolean)
      : [],
    keywords: (/\bkeywords:\s*\[([^\]]*)\]/.exec(body)?.[1] ?? '')
      .split(',')
      .map((s) => s.trim().replace(/^'|'$/g, ''))
      .filter(Boolean),
  })
}

/* what each of those files imports, resolved against the tree */
function depsOf(file) {
  if (!file) return []
  const abs = resolve(root, file)
  let src
  try {
    src = readFileSync(abs, 'utf8')
  } catch {
    return []
  }
  const out = new Set()
  const re = /(?:^|\n)\s*import\s+(?:[\s\S]*?\sfrom\s+)?['"]([^'"]+)['"]/g
  let d
  while ((d = re.exec(src))) {
    const spec = d[1]
    if (spec.startsWith('.')) {
      /* resolve the relative specifier to a real file in the tree */
      const base = resolve(dirname(abs), spec)
      for (const cand of [base, `${base}.ts`, `${base}.tsx`, `${base}/index.ts`, `${base}/index.tsx`]) {
        try {
          readFileSync(cand, 'utf8')
          out.add(relative(root, cand))
          break
        } catch {
          /* not this one */
        }
      }
    } else {
      out.add(spec) // an external package, named as it is imported
    }
  }
  return [...out].sort()
}

for (const a of apps) a.dependencies = depsOf(a.file)

/* the files that are present but not claimed by any app still belong in the
   listing, so the index covers the whole directory */
const claimed = new Set(apps.map((a) => a.file).filter(Boolean))
const orphans = readdirSync(appsDir)
  .filter((f) => /\.(tsx|ts)$/.test(f))
  .map((f) => `src/apps/${f}`)
  .filter((f) => !claimed.has(f))
  .sort()

const header = `/* Generated by scripts/gen-appindex.mjs from src/apps — do not edit by hand.
 *
 * One record per application: its name, a one-line summary, the description
 * shown in the menu and the store, the file that implements it, and every
 * module that file imports. \`src/os/appindex.ts\` is read by the desktop to lay
 * out /usr/share/applications, so the filesystem and the code agree.
 */
`
const body =
  header +
  `export interface AppIndexEntry {\n` +
  `  id: string\n  name: string\n  summary: string\n  description: string\n  file: string\n` +
  `  categories: string[]\n  keywords: string[]\n  dependencies: string[]\n}\n\n` +
  `export const APP_INDEX: AppIndexEntry[] = ${JSON.stringify(apps, null, 2)}\n\n` +
  `/** files in src/apps that belong to no registered app (shared helpers) */\n` +
  `export const APP_SHARED_FILES: string[] = ${JSON.stringify(orphans, null, 2)}\n`

writeFileSync(resolve(root, 'src/os/appindex.ts'), body)
console.log(`  wrote src/os/appindex.ts — ${apps.length} apps, ${orphans.length} shared files`)
